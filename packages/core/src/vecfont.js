function expand(defs) {
  var out = {};
  for (var ch in defs) {
    var paths = [], dots = [];
    var cmds = defs[ch];
    for (var i = 0; i < cmds.length; i++) {
      var c = cmds[i];
      if (c[0] === 'P') {
        paths.push(c.slice(1));
      } else if (c[0] === 'D') {
        dots.push([c[1], c[2]]);
      } else if (c[0] === 'A') {
        var cx = c[1], cy = c[2], rx = c[3], ry = c[4], a0 = c[5], a1 = c[6];
        var span = Math.abs(a1 - a0);
        var n = Math.max(8, Math.ceil(span / 12));
        var pts = [];
        for (var k = 0; k <= n; k++) {
          var a = (a0 + (a1 - a0) * (k / n)) * Math.PI / 180;
          pts.push(cx + rx * Math.cos(a), cy + ry * Math.sin(a));
        }
        paths.push(pts);
      }
    }
    out[ch] = { p: paths, d: dots };
  }
  return out;
}

