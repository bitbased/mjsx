// Package the mjsx web renderer for a device to serve from flash.
//
//   bun backends/esp32/tools/gen-remote-assets.mjs <out-dir>
//
// Bun-bundles the REAL rasterizer (pure-js backend + the whole font
// system, same bundle the sim's browser mirror uses), gzips it, and
// emits remote_assets.h: a PROGMEM byte array a firmware can hand to
// "GET /mjsx-backend.js" with Content-Encoding: gzip. The device keeps
// its native renderer; only the BROWSER pays for the HD faces — which is
// the point of serving them rather than rendering with them on-chip.
import { gzipSync } from "node:zlib";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = process.argv[2];
if (!outDir) { console.error("usage: bun gen-remote-assets.mjs <out-dir>"); process.exit(1); }

const entry = join(here, "../../http/src/client-backend.js");
const built = await Bun.build({ entrypoints: [entry], target: "browser", format: "iife", minify: true });
if (!built.success) { console.error("bundle failed"); process.exit(1); }
const js = await built.outputs[0].text();
const gz = gzipSync(Buffer.from(js, "utf8"), { level: 9 });

let h = "#pragma once\n";
h += "// GENERATED by mjsx backends/esp32/tools/gen-remote-assets.mjs - do not edit.\n";
h += `// ${js.length} bytes of JS, ${gz.length} gzipped. Serve with Content-Encoding: gzip.\n`;
h += `const unsigned MJSX_BACKEND_JS_GZ_LEN = ${gz.length};\n`;
h += "const uint8_t MJSX_BACKEND_JS_GZ[] PROGMEM = {\n";
for (let i = 0; i < gz.length; i += 24) {
  h += "  " + Array.from(gz.subarray(i, i + 24)).join(",") + ",\n";
}
h += "};\n";
writeFileSync(join(outDir, "remote_assets.h"), h);
console.log(`remote_assets.h: ${js.length} bytes js -> ${gz.length} gzipped`);
